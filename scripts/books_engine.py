def book_nodes(book: dict, url: str) -> list:
    crumbs = [("Home", f"{DOMAIN}/"), ("Books", HUB_URL), (book["title"], url)]
    nodes = [
        bc.webpage_node(url, book["title"], book["seoDescription"],
                        f"{url}#breadcrumb"),
        bc.breadcrumb_node({"id": f"{url}#breadcrumb",
                            "items": [(n, u) for n, u in crumbs]}),
    ]

    book_node = {
        "@type": "Book",
        "@id": f"{url}#book",
        "name": book["title"],
        "url": url,
        "description": book["description"],
        "author": {"@type": "Person", "name": book["author"]},
        "genre": label_for(SUBJECT_LABELS, book["subject"]),
    }
    # Optional schema fields, added only when the file actually carries them.
    # A short book JSON omits publisher, edition and topic list entirely -
    # emitting them as empty nodes would be markup rich results drop, not
    # markup rich results reward.
    if book["languages"]:
        book_node["inLanguage"] = [str(lang) for lang in book["languages"]]
    if book["publisher"]:
        book_node["publisher"] = {"@type": "Organization",
                                  "name": book["publisher"]}
    if book["edition"]:
        book_node["bookEdition"] = book["edition"]
    if book["topicsCovered"]:
        book_node["about"] = [{"@type": "Thing", "name": t}
                              for t in book["topicsCovered"]]
    if book.get("cover"):
        size = image_size(ROOT / book["cover"]) or (600, 900)
        book_node["image"] = {"@type": "ImageObject",
                              "url": f'{DOMAIN}/{book["cover"]}',
                              "width": size[0], "height": size[1]}
    # No `offers` node: this site holds no price. Price comparison and live
    # offers are a documented future feature - emitting an Offer without a
    # price would be markup Google rejects, not markup Google rewards.
    nodes.append(book_node)
    nodes[0]["mainEntity"] = {"@id": f"{url}#book"}

    faq = faq_for(book)
    nodes.append({
        "@type": "FAQPage",
        "@id": f"{url}#faq",
        "mainEntity": [{
            "@type": "Question",
            "name": item["q"],
            "acceptedAnswer": {"@type": "Answer", "text": item["a"]},
        } for item in faq],
    })
    return nodes


