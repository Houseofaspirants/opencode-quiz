# --------------------------------------------------------------------- util --
def esc(value) -> str:
    return html_mod.escape(str(value if value is not None else ""), quote=True)


def read_json(path: Path, default=None):
    try:
        return json.loads(path.read_text(encoding="utf-8"))
    except FileNotFoundError:
        return default
    except json.JSONDecodeError as exc:
        raise BuildError(f"{path.relative_to(ROOT)}: invalid JSON: {exc}")


def write_text(path: Path, text: str, encoding: str = "utf-8") -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding=encoding)


class BuildError(Exception):
    """A book failed validation - the build stops, nothing is half-published."""


def humanize(value: str) -> str:
    return re.sub(r"\b([a-z])", lambda m: m.group(1).upper(),
                  re.sub(r"[-_]+", " ", str(value)).strip())


def image_size(path: Path):
    """(width, height) for the formats a cover may arrive as, else None.

    width/height on <img> is what reserves the box before the file decodes, so
    the page cannot know it without reading the header. Standard library only -
    the builder runs on a bare Python 3.12 with no imaging package installed.
    """
    try:
        blob = path.read_bytes()
    except OSError:
        return None
    if blob[:8] == b"\x89PNG\r\n\x1a\n" and blob[12:16] == b"IHDR":
        return struct.unpack(">II", blob[16:24])
    if blob[:6] in (b"GIF87a", b"GIF89a"):
        return struct.unpack("<HH", blob[6:10])
    if blob[:4] == b"RIFF" and blob[8:12] == b"WEBP":
        if blob[12:16] == b"VP8X" and len(blob) >= 30:
            return (1 + int.from_bytes(blob[24:27], "little"),
                    1 + int.from_bytes(blob[27:30], "little"))
        if blob[12:16] == b"VP8 " and len(blob) >= 30:
            # 14-bit little-endian; the top two bits are the scale factor.
            return (int.from_bytes(blob[26:28], "little") & 0x3FFF,
                    int.from_bytes(blob[28:30], "little") & 0x3FFF)
        if blob[12:16] == b"VP8L" and len(blob) >= 25 and blob[20] == 0x2F:
            b0, b1 = blob[21], blob[22]
            return ((b1 & 0x3F) << 8 | b0) + 1, \
                   ((b1 >> 6) | blob[23] << 2 | blob[24] << 10) + 1
    if blob[:2] == b"\xff\xd8":                      # JPEG: walk to a SOF marker
        i = 2
        while i + 9 < len(blob):
            if blob[i] != 0xFF:
                i += 1
                continue
            marker = blob[i + 1]
            if marker in (0xD8, 0x01) or 0xD0 <= marker <= 0xD7:
                i += 2
                continue
            length = int.from_bytes(blob[i + 2:i + 4], "big")
            if 0xC0 <= marker <= 0xCF and marker not in (0xC4, 0xC8, 0xCC):
                h, w = struct.unpack(">HH", blob[i + 5:i + 9])
                return w, h
            i += 2 + length
    return None


# ---------------------------------------------------------------- validation --
# What a book MUST carry. The shelf shows only cover, title, author, one
# recommendation line and the CTA, so a new book is a short file; everything
# the schema or the related-content ranker still wants but the reader never
# sees lives in OPTIONAL_DEFAULTS and is filled by normalize() before any of
# this module reads it. No reader guards for a missing key.
REQUIRED_STR = ("id", "slug", "title", "author", "subject",
                "recommendation", "keywords", "lastUpdated")
REQUIRED_LIST = ()
REQUIRED_TEXT = ("seoTitle", "seoDescription")

# Optional fields and the value they fall back to. `list` defaults are copied,
# so two books never share an array. Filled in normalize() after validation,
# which is why an absent field is never a validation error for these.
OPTIONAL_DEFAULTS = {
    "publisher": "",
    "difficulty": "",
    "edition": "",
    "bestFor": "",
    "buyIf": "",
    "avoidIf": "",
    "howToUse": "",
    "description": "",
    "languages": [],
    "examTags": [],
    "pros": [],
    "cons": [],
    "topicsCovered": [],
}

# A recommendation is ONE line: two lines at a phone's card width is ~110
# characters, and the shelf clamps to two lines anyway. Capping it here keeps
# an editor from quietly turning the shelf back into a review.
RECOMMENDATION_MAX = 140


def validate(book: dict, where: str, subject_ids: set, seen: set,
             known_book_ids: set, reserved: set) -> list:
    """Return a list of human-readable problems. Empty means the book publishes."""
    problems = []

    def need(key, kind=str):
        if key not in book:
            problems.append(f"missing required field `{key}`")
            return None
        if not isinstance(book[key], kind) or (
                kind is str and not str(book[key]).strip()):
            problems.append(f"`{key}` must be a non-empty "
                            f"{kind.__name__}")
            return None
        return book[key]

    for key in REQUIRED_STR:
        need(key)
    for key in REQUIRED_TEXT:
        need(key)
    for key in REQUIRED_LIST:
        if key not in book:
            problems.append(f"missing required field `{key}`")
        elif not isinstance(book[key], list) or not book[key]:
            problems.append(f"`{key}` must be a non-empty array")
        elif any(not isinstance(v, str) or not v.strip() for v in book[key]):
            problems.append(f"`{key}` may only hold non-empty strings")

    bid = str(book.get("id", ""))
    if bid and not re.fullmatch(r"[a-z0-9][a-z0-9-]*", bid):
        problems.append(f"`id` {bid!r} must be a lowercase URL slug")
    if bid and bid != where:
        problems.append(f"`id` {bid!r} must equal its file name ({where})")
    if bid in seen:
        problems.append(f"duplicate id {bid!r}")
    if bid and bid in reserved:
        problems.append(
            f"id {bid!r} collides with content/book-recommendations/{bid}.md - "
            f"both would publish {f'book-{bid}.html'}")
    if bid and bid not in known_book_ids:
        problems.append(f"no entry for {bid!r} in config/affiliate-links.json - "
                        f"the shelf would show a book with no way to get it")
    if "slug" in book and book.get("slug") != bid:
        problems.append(f"`slug` {book.get('slug')!r} must equal `id`")

    subject = str(book.get("subject", ""))
    if subject and subject_ids and subject not in subject_ids:
        problems.append(f"`subject` {subject!r} is not an id in data/subjects.json")

    if "difficulty" in book and book["difficulty"] not in DIFFICULTY_ORDER:
        problems.append(f"`difficulty` {book['difficulty']!r} must be one of "
                        f"{', '.join(DIFFICULTY_ORDER)}")

    rating = book.get("rating")
    if rating is not None:
        if not isinstance(rating, (int, float)) or not 0 <= float(rating) <= 5 \
                or round(float(rating) * 2) != float(rating) * 2:
            problems.append(f"`rating` {rating!r} must be 0-5 in half steps")

    for key, lo, hi, label in (("seoTitle", 1, 60, "must be 1-60 characters"),
                               ("seoDescription", 140, 160,
                                "must be 140-160 characters")):
        if isinstance(book.get(key), str) and book[key].strip():
            if not lo <= len(book[key]) <= hi:
                problems.append(f"`{key}` is {len(book[key])} chars, {label}")

    if "featured" in book and not isinstance(book["featured"], bool):
        problems.append("`featured` must be true or false")
    if "priority" in book and not re.fullmatch(r"0\.\d", str(book["priority"])):
        problems.append(f"`priority` {book['priority']!r} must look like \"0.7\"")
    if "lastUpdated" in book and not re.fullmatch(
            r"20\d{2}-\d{2}-\d{2}", str(book.get("lastUpdated", ""))):
        problems.append(f"`lastUpdated` {book.get('lastUpdated')!r} is not YYYY-MM-DD")

    # The shelf's whole message is this one line, so it stays one line.
    rec = str(book.get("recommendation", ""))
    if rec and len(rec) > RECOMMENDATION_MAX:
        problems.append(f"`recommendation` is {len(rec)} chars - the shelf shows "
                        f"one line of at most {RECOMMENDATION_MAX}")
    if "group" in book and len(str(book["group"])) > 40:
        problems.append("`group` must be a short subject name (max 40 chars)")

    # The affiliate-link quarantine: content may never hold a destination.
    # The related* arrays are the one exception, because they are site-internal
    # navigation (books.html, study-notes.html) - they are validated below.
    for key, value in book.items():
        if key in RELATED_KEYS:
            continue
        if key.lower() in FORBIDDEN_KEYS:
            problems.append(f"`{key}` is a link - links live in "
                            f"config/affiliate-links.json, never in book content")
            continue
        text = json.dumps(value, ensure_ascii=False).lower()
        if any(host in text for host in FORBIDDEN_HOSTS):
            problems.append(f"`{key}` contains an outbound host - links live in "
                            f"config/affiliate-links.json")
            break

    for key in RELATED_KEYS:
        value = book.get(key)
        if value is None:
            continue
        if not isinstance(value, list):
            problems.append(f"`{key}` must be an array")
            continue
        for entry in value:
            if key == "relatedBooks":
                if not isinstance(entry, str) or not entry:
                    problems.append("`relatedBooks` must hold book ids (strings)")
                elif entry not in known_book_ids:
                    problems.append(f"`relatedBooks` -> {entry!r} is not a known "
                                    f"book id")
                continue
            if not isinstance(entry, dict) or "label" not in entry \
                    or "href" not in entry:
                problems.append(f"`{key}` entries need `label` and `href`")
                continue
            href = str(entry["href"])
            if href.startswith(("http://", "https://", "//", "mailto:", "tel:", "#")):
                problems.append(f"`{key}` -> {href!r} must be a site-relative link "
                                f"like `study-notes.html`; outbound destinations "
                                f"belong in config/affiliate-links.json")

    if str(book.get("cover", "")).strip():
        cover = ROOT / str(book["cover"])
        if not cover.is_file():
            problems.append(f"`cover` {book['cover']!r} is not on disk - drop the "
                            f"image into assets/books/covers/ or set cover to \"\"")

    return problems


def normalize(book: dict) -> dict:
    """Fill every optional field once, after validation passes.

    Callers below then read book["publisher"], book["examTags"] and friends
    without guarding: a four-field JSON file publishes the same way a
    twenty-field one does. `description` falls back to `recommendation` (the
    two serve different readers - schema and ranking see the first, the shelf
    the second), and `group` falls back to the book's subject name so the
    shelf groups correctly with no group written at all.
    """
    for key, default in OPTIONAL_DEFAULTS.items():
        if key not in book:
            book[key] = list(default) if isinstance(default, list) else default
    if not str(book.get("description", "")).strip():
        book["description"] = book.get("recommendation", "")
    if not str(book.get("group", "")).strip():
        book["group"] = label_for(SUBJECT_LABELS, str(book.get("subject", "")))
    return book


# -------------------------------------------------------------- affiliates --
def load_affiliates() -> dict:
    if not AFFILIATE_FILE.exists():
        raise BuildError("config/affiliate-links.json is missing - the Books "
                         "system cannot resolve a single destination without it")
    data = read_json(AFFILIATE_FILE, {})
    providers = [p for p in (data.get("providers") or [])
                 if isinstance(p, dict) and p.get("id")]
    if not providers:
        raise BuildError("config/affiliate-links.json defines no providers")
    for p in providers:
        p.setdefault("label", humanize(p["id"]))
        p.setdefault("shortLabel", p["label"])
        p.setdefault("host", "")
        p.setdefault("external", True)
    settings = data.get("settings") or {}
    settings.setdefault("rel", "sponsored noopener nofollow")
    settings.setdefault("query", {})
    settings.setdefault("amazonAssociateTag", "")
    return {"settings": settings, "providers": providers,
            "books": {k: v for k, v in (data.get("books") or {}).items()
                      if not k.startswith("$")}}


def with_tracking(url: str, provider: dict, settings: dict) -> str:
    """Merge the tracking config into a destination. Existing keys always win."""
    if not provider.get("external", True):
        return url                                  # our own pages: no utm noise
    parts = urlsplit(url)
    query = dict(parse_qsl(parts.query, keep_blank_values=True))
    for key, value in (settings.get("query") or {}).items():
        query.setdefault(key, value)
    if provider["id"] == "amazon" and settings.get("amazonAssociateTag"):
        query["tag"] = settings["amazonAssociateTag"]
    return urlunsplit((parts.scheme, parts.netloc, parts.path,
                       urlencode(query), parts.fragment))


def providers_for(book_id: str, aff: dict) -> list:
    """Ordered, available providers only. Absent/empty == not available."""
    owned = aff["books"].get(book_id) or {}
    out = []
    for provider in aff["providers"]:
        raw = owned.get(provider["id"])
        if not isinstance(raw, str) or not raw.strip():
            continue
        target = with_tracking(raw.strip(), provider, aff["settings"])
        pid = provider["id"]
        external = bool(provider.get("external", True))
        out.append({
            "id": pid,
            "label": provider["label"],
            "shortLabel": provider["shortLabel"],
            "external": external,
            # One click: the destination IS the href, so the reader lands on
            # the shop straight from the shelf. No popup, no /go/ stub in
            # between. `with_tracking` has already merged the UTM params and
            # the Associates tag onto it, and `target` is kept beside it for
            # anything that wants the plain destination.
            "href": target,
            "target": target,
            # the rel the shelf must put on an outbound anchor, read from the
            # config so no page or script ever hardcodes a link policy.
            "rel": (str((aff.get("settings") or {}).get("rel") or "")
                    if external else ""),
        })
    return out


