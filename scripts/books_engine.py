def load_books(subject_ids: set, reserved: set, affiliate_ids: set) -> list:
    if not BOOKS_DIR.is_dir():
        return []
    loaded, errors = [], []
    for path in sorted(BOOKS_DIR.glob("*.json")):
        if path.name.startswith("$"):
            continue
        stem = path.stem
        try:
            book = json.loads(path.read_text(encoding="utf-8"))
        except json.JSONDecodeError as exc:
            errors.append(f"content/books/{path.name}: invalid JSON: {exc}")
            continue
        if not isinstance(book, dict):
            errors.append(f"content/books/{path.name}: must hold one JSON object")
            continue
        for problem in validate(book, stem, subject_ids, {b["id"] for b in loaded},
                                affiliate_ids, reserved):
            errors.append(f"content/books/{path.name}: {problem}")
        loaded.append(book)
    if errors:
        raise BuildError("\n".join(f"  \u2716 {e}" for e in errors))
    loaded.sort(key=lambda b: (-bool(b.get("featured")), str(b.get("title")).lower()))
    return loaded


# The shelf has ONE dimension: the subject a book belongs to. `group` is the
# display name each book carries ("Polity", "Punjab GK", ...) and the rows are
# always derived from the books that exist (see facets()), so a new subject
# appears the moment a book does - no chip list to maintain, nothing hardcoded
# in a page or in a script.
FACET_SPEC = (
    ("group", "Subject", "group", "is"),
)


def facets(books: list) -> dict:
    """The subject groups, derived from the books that exist.

    Exactly the shape every former facet had - a label, how a chip applies to
    a record, and the rows that actually exist - which is what
    scripts/seo_check.py validates and what the shelf renders. There is simply
    only one of them now: exam, publisher, author, language, difficulty, the
    featured flag and the rating buckets were all filters this page dropped.
    """
    counts = {}
    for book in books:
        value = str(book.get("group") or "")
        if value:
            counts[value] = counts.get(value, 0) + 1
    rows = [{"id": v, "label": v, "count": c} for v, c in counts.items()]
    rows.sort(key=lambda r: (-r["count"], r["label"].lower()))
    return {key: {"key": key, "label": label, "field": field, "match": match,
                  "rows": rows}
            for key, label, field, match in FACET_SPEC}


def haystack(book: dict) -> str:
    """One pre-lowercased string per book: the whole surface the shelf search
    matches against. Built here so the browser never has to know which fields
    matter - adding a searchable field is an engine change, not a JS change."""
    parts = [book.get("id", ""), book.get("title", ""), book.get("subtitle", ""),
             book.get("author", ""), book.get("group", ""),
             book.get("recommendation", ""),
             book.get("publisher", ""), book.get("edition", ""),
             book.get("difficulty", ""), book.get("description", ""),
             book.get("keywords", ""), book.get("bestFor", ""),
             book.get("subject", ""), label_for(SUBJECT_LABELS, book["subject"])]
    parts += book.get("topicsCovered", []) + book.get("languages", [])
    parts += [label_for(EXAM_LABELS, e) for e in book.get("examTags", [])]
    return re.sub(r"\s+", " ", " ".join(str(p) for p in parts if p)).strip().lower()


def shelf_record(book: dict, providers: list) -> dict:
    size = image_size(ROOT / book["cover"]) if book.get("cover") else None
    return {
        "id": book["id"],
        "slug": book.get("slug", book["id"]),
        "title": book["title"],
        "subtitle": book.get("subtitle", ""),
        "author": book["author"],
        # The shelf card's two new fields: the subject it files itself under
        # and the one line the card prints under the author.
        "group": book["group"],
        "recommendation": book["recommendation"],
        "publisher": book["publisher"],
        "cover": book.get("cover", ""),
        "coverW": size[0] if size else 0,
        "coverH": size[1] if size else 0,
        "subject": book["subject"],
        "subjectLabel": label_for(SUBJECT_LABELS, book["subject"]),
        "difficulty": book["difficulty"],
        "rating": book.get("rating"),
        "edition": book["edition"],
        "languages": book["languages"],
        "examTags": book["examTags"],
        "examLabels": [label_for(EXAM_LABELS, e) for e in book["examTags"]],
        "description": book["description"],
        "bestFor": book["bestFor"],
        "buyIf": book["buyIf"],
        "avoidIf": book["avoidIf"],
        "howToUse": book["howToUse"],
        "featured": bool(book.get("featured")),
        "file": f'book-{book["id"]}.html',
        "url": f'{DOMAIN}/book-{book["id"]}',
        "lastUpdated": book["lastUpdated"],
        "providers": [{k: p[k] for k in
                       ("id", "label", "shortLabel", "external", "href", "rel")}
                      for p in providers],
        "search": haystack(book),
    }


def build() -> dict:
    """Publish everything. Called by scripts/build_index.py."""
    global BOOK, SUBJECT_LABELS, EXAM_LABELS, ALL_BOOKS, BOOK_INDEX

    BOOK = load_affiliates()
    SUBJECT_LABELS, EXAM_LABELS = load_labels()
    subject_ids = set(SUBJECT_LABELS)

    affiliate_ids = set(BOOK["books"])
    reserved = {p.stem for p in (ROOT / "content" / "book-recommendations").glob("*.md")
                if p.name != "README.md"} if (
                    ROOT / "content" / "book-recommendations").is_dir() else set()

    # Optional fields are filled before anything downstream reads them, so a
    # short JSON file (id, title, author, group, recommendation, cover) builds
    # the same page a full one does.
    books = [normalize(b) for b in load_books(subject_ids, reserved, affiliate_ids)]
    index = read_json(ROOT / "data" / "index.json", {}) or {}
    pool = manifest_pool()

    BOOK_INDEX = {b["id"]: {"file": f'book-{b["id"]}.html', "title": b["title"]}
                  for b in books}
    ALL_BOOKS = []
    for book in books:
        ALL_BOOKS.append({
            "id": book["id"],
            "file": f'book-{book["id"]}.html',
            "title": book["title"],
            # No `difficulty` on the seed: content_engine.score()'s
            # difficulty/category branch adds a *string* to the running total
            # (a latent defect in shared ranking code), so two records with the
            # same difficulty would raise. Facet overlap on subject, exam and
            # topics is what relates two books anyway.
            "seed": {
                "file": f'book-{book["id"]}.html',
                "collection": "books",
                "title": book["title"],
                "description": book["description"],
                "subjects": [book["subject"]],
                "exams": book["examTags"],
                "tags": book["topicsCovered"],
                "featured": bool(book.get("featured")),
            },
        })

    produced = set()
    shelf, items, pages, redirects = [], [], [], []
    cover_count = 0

    for book in books:
        bid = book["id"]
        file = f"book-{bid}.html"
        url = f"{DOMAIN}/book-{bid}"
        providers = providers_for(bid, BOOK)

        seed = next(b["seed"] for b in ALL_BOOKS if b["id"] == bid)
        related = related_for(book, seed, pool, quiz_pool(index, book["subject"]))

        write_text(ROOT / file, book_page(book, providers, related,
                                          book_nodes(book, url)))
        produced.add(file)

        # No redirect stub is written: every provider href already IS the
        # destination (see providers_for), so there is nothing to hop through.
        # `redirects` stays in the manifest as an empty list for shape
        # compatibility, and the prune pass below deletes any /go/ stub an
        # earlier build left behind.

        if book.get("cover"):
            cover_count += 1
        shelf.append(shelf_record(book, providers))
        items.append({
            "id": bid, "file": file, "url": url,
            "title": book["seoTitle"], "description": book["seoDescription"],
            "name": book["title"], "author": book["author"],
            "publisher": book["publisher"], "subject": book["subject"],
            "exams": book["examTags"], "languages": book["languages"],
            "difficulty": book["difficulty"], "rating": book.get("rating"),
            "featured": bool(book.get("featured")), "cover": book.get("cover", ""),
            "topics": book["topicsCovered"], "keywords": book["keywords"],
            "lastUpdated": book["lastUpdated"],
        })
        pages.append({"file": file, "url": url, "title": book["seoTitle"],
                      "description": book["seoDescription"],
                      "priority": str(book.get("priority", "0.7"))})

    # --- prune: a deleted book must not leave a page or a redirect behind ----
    previous = read_json(MANIFEST_FILE, {}) or {}
    for record in list(previous.get("pages", [])) + list(previous.get("redirects", [])):
        stale = str(record.get("file", ""))
        if stale and stale not in produced and stale != HUB_FILE:
            path = ROOT / stale
            if path.is_file() and MARKER in path.read_text(encoding="utf-8", errors="replace"):
                path.unlink()
    if previous.get("redirects"):
        gone = GO_DIR
        for directory in sorted((p for p in gone.rglob("*") if p.is_dir()),
                                key=lambda p: len(p.parts), reverse=True):
            try:
                directory.rmdir()
            except OSError:
                pass

    filters = facets(books)
    write_text(SHELF_FILE, json.dumps({
        "$note": ("GENERATED by scripts/books_engine.py - do not edit. Source of "
                  "truth: content/books/*.json (book content) and "
                  "config/affiliate-links.json (links). `books` is what the shelf "
                  "renders (including `search`, the pre-lowercased string the "
                  "shelf search matches on), `filters` describes every filter "
                  "dimension derived from those books (label + how a chip "
                  "matches a record + the rows that exist) and `count` is the "
                  "shelf size. Add a book by dropping a JSON file into "
                  "content/books/ and rebuilding - never edit this file."),
        "count": len(shelf),
        "filters": filters,
        "books": shelf,
    }, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")

    write_text(MANIFEST_FILE, json.dumps({
        "$note": ("GENERATED by scripts/books_engine.py - do not edit. The SEO "
                  "registry for the Books system: `pages` is read by BOTH index "
                  "builders to put every book in sitemap.xml, `hubs`/`items` are "
                  "read by scripts/seo_check.py to gate title, description, "
                  "canonical, schema and sitemap parity. `redirects` lists the "
                  "affiliate hops the engine owns so it can prune them. "
                  "No timestamps: a rebuild is byte-identical or CI fails."),
        "version": 1,
        "domain": DOMAIN,
        "generatedBy": "scripts/books_engine.py",
        "hubs": [{
            "collection": "books", "file": HUB_FILE, "url": HUB_URL,
            "title": "Recommended Books for Punjab Exams | House of Aspirants",
            "description": ("Compare preparation books for Punjab Police, PSSSB, "
                            "PPSC, SSC, banking and railway exams - what each one "
                            "covers, who it suits and who should skip it."),
            "count": len(shelf),
        }],
        "pages": pages,
        "items": items,
        "redirects": redirects,
        "counts": {"books": len(shelf), "covers": cover_count,
                   "providers": len(BOOK["providers"])},
    }, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")

    for page in pages:
        found = main_links((ROOT / page["file"]).read_text(encoding="utf-8"))
        if len(found) < 5:
            raise BuildError(f'{page["file"]}: only {len(found)} contextual links '
                             f'inside <main> - the link floor is 5')

    print(f"  \u2714 books: {len(shelf)} published, {len(redirects)} redirect(s), "
          f"{cover_count}/{len(shelf)} cover(s), "
          f"{sum(1 for f in filters.values() if f)} facet(s)")
    return {"books": len(shelf), "pages": len(pages), "redirects": len(redirects)}


def main_links(html_text: str) -> set:
    """Exactly what scripts/seo_check.py counts against the link floor."""
    match = re.search(r"<main[^>]*>(.*?)</main>", html_text, re.S)
    return link_floor(match.group(1)) if match else set()


