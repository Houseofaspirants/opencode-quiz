def manifest_pool():
    """Published documents from the content builder, shaped for score()."""
    cm = read_json(ROOT / "data" / "content-manifest.json", {}) or {}
    pool = []
    for item in cm.get("items", []):
        if not item.get("file"):
            continue
        pool.append({
            "file": item["file"],
            "url": item.get("url") or f"{DOMAIN}/{item['file'][:-5]}",
            "title": item.get("title") or "",
            "description": item.get("description") or "",
            "collection": item.get("collection") or "",
            "subjects": item.get("subjects") or [],
            "exams": item.get("exams") or [],
            "tags": item.get("tags") or [],
            "lang": item.get("lang") or "en",
            "published": item.get("published") or "",
        })
    return pool


def quiz_pool(index: dict, subject_id: str):
    """Live practice sets for this book's subject, same subject first."""
    out = []
    for pos, subject in enumerate(index.get("subjects", [])):
        same = subject.get("id") == subject_id
        for topic in subject.get("topics", []):
            if not topic.get("available"):
                continue
            cat = topic.get("category") or ""
            href = (f'quiz.html?subject={subject["id"]}&topic={topic["id"]}'
                    + (f"&category={cat}" if cat else ""))
            out.append({
                "href": href,
                "label": topic.get("name") or topic["id"],
                "eyebrow": subject.get("name") or subject["id"],
                "rank": (0 if same else 2) + (0.1 if (same and cat) else 0) + pos * 0.01,
            })
    out.sort(key=lambda r: r["rank"])
    return out


def related_for(book: dict, seed: dict, pool: list, quizzes: list):
    """Every related group, derived. Seeds from the book file come first and
    the automatic matches follow - with no seed at all the groups still fill,
    so no editor ever has to hand-link two books together."""
    def seed_links(key):
        return [{"href": e["href"], "label": e["label"], "eyebrow": ""}
                for e in (book.get(key) or [])]

    def ranked(collections, limit=MAX_RELATED):
        picked, seen = [], set()
        for rec, _score, _why in bc_rank(seed,
                                         [p for p in pool
                                          if p["collection"] in collections],
                                         limit=limit):
            if rec["file"] in seen:
                continue
            seen.add(rec["file"])
            picked.append({"href": rec["file"], "label": rec["title"],
                           "eyebrow": "", "sub": rec["description"]})
        return picked

    subject = book["subject"]
    subject_name = label_for(SUBJECT_LABELS, subject)

    notes = seed_links("relatedNotes") + ranked(NOTE_COLLECTIONS)
    mcqs = ranked(MCQ_COLLECTIONS)
    pyq = ranked(PYQ_COLLECTIONS)
    ca = seed_links("relatedCurrentAffairs") + ranked(CA_COLLECTIONS)
    # The curated `relatedQuizzes` seeds are Practice destinations
    # (subject.html, cluster pages), so they belong with the practice slots.
    practice = (seed_links("relatedQuizzes")
                + [{"href": "mock.html", "label": "Mock tests",
                    "eyebrow": "Practice"},
                   {"href": "quiz.html?mode=daily", "label": "Daily challenge",
                    "eyebrow": "Practice"}]
                + quizzes[:MAX_RELATED])

    # Hubs are real pages, so an empty collection still lands the reader
    # somewhere honest instead of on an empty box.
    if not notes:
        notes = [{"href": "study-notes.html", "label": "Study notes",
                  "eyebrow": "Study"},
                 {"href": "articles.html", "label": "Study guides",
                  "eyebrow": "Study"},
                 {"href": f"study.html?subject={subject}",
                  "label": f"{subject_name} in Study", "eyebrow": "Study"}]
    if not mcqs:
        mcqs = [{"href": "expected-mcqs.html", "label": "Topic-wise expected MCQs",
                 "eyebrow": "Practice"},
                {"href": "daily-practice.html", "label": "Daily practice sets",
                 "eyebrow": "Practice"}]
    if not pyq:
        pyq = [{"href": "previous-year-questions.html",
                "label": "Previous Year Questions", "eyebrow": "Papers"},
               {"href": "pyq.html", "label": "Solved papers by exam",
                "eyebrow": "Papers"}]
    if not ca:
        ca = [{"href": "current-affairs.html", "label": "Current affairs",
               "eyebrow": "Current affairs"},
              {"href": "magazine.html", "label": "Monthly magazine",
               "eyebrow": "Current affairs"}]

    self_file = f'book-{book["id"]}.html'
    books = [{"href": f'book-{rid}.html',
              "label": BOOK_INDEX.get(rid, {}).get("title", humanize(rid)),
              "eyebrow": ""}
             for rid in (book.get("relatedBooks") or []) if rid in BOOK_INDEX]
    seen_books = {e["href"] for e in books} | {self_file}
    for rec, _score, _why in bc_rank(seed,
                                     [b["seed"] for b in ALL_BOOKS
                                      if b["file"] not in seen_books],
                                     limit=MAX_RELATED):
        if rec["file"] in seen_books:
            continue
        seen_books.add(rec["file"])
        books.append({"href": rec["file"], "label": rec["title"], "eyebrow": ""})

    def cut(rows):
        out, seen = [], set()
        for row in rows:
            href = str(row["href"]).split("#", 1)[0]
            if not href or href in seen:
                continue
            seen.add(href)
            out.append(row)
            if len(out) >= MAX_RELATED:
                break
        return out

    return {"notes": cut(notes), "mcqs": cut(mcqs), "practice": cut(practice),
            "pyq": cut(pyq), "currentAffairs": cut(ca), "books": cut(books)}


def bc_rank(seed, pool, limit=MAX_RELATED):
    """content_engine.score() over a pool, sorted deterministically."""
    ranked = []
    for cand in pool:
        value, why = score(seed, cand, same_collection=False)
        if value <= 0:
            continue
        ranked.append((-value, str(cand.get("file") or cand.get("url") or ""), cand, why))
    ranked.sort(key=lambda t: (t[0], t[1]))
    return [(cand, -neg, why) for neg, _key, cand, why in ranked[:limit]]


