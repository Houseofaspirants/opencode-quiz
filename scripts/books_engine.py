def load_labels():
    subjects = read_json(ROOT / "data" / "subjects.json", {})
    subject_labels = {s["id"]: s.get("name") or humanize(s["id"])
                      for s in subjects.get("subjects", [])}

    exams = read_json(ROOT / "data" / "exams.json", {})
    exam_labels = {e["id"]: e.get("name") or humanize(e["id"])
                   for e in exams.get("exams", [])}
    for key, value in (exams.get("tagLabels") or {}).items():
        exam_labels.setdefault(key, value)
    return subject_labels, exam_labels


def label_for(mapping: dict, key: str) -> str:
    return mapping.get(key) or humanize(key)


