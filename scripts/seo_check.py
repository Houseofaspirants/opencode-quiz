def head_of(html: str) -> str:
    m = re.search(r"<head>(.*?)</head>", html, re.S)
    return m.group(1) if m else ""


def meta(html: str, name: str) -> str:
    m = re.search(r'<meta\s+(?:name|property)="%s"\s+content="([^"]*)"' % re.escape(name), head_of(html))
    return m.group(1) if m else ""


def canonical(html: str) -> str:
    m = re.search(r'<link\s+rel="canonical"\s+href="([^"]*)"', head_of(html))
    return m.group(1) if m else ""


def page_url(rel: str) -> str:
    """The URL a content index page publishes at.

    `pyq/<exam>/index.html` is a directory index, so it publishes at
    `/pyq/<exam>` and never at `.../index`. Every other page keeps the plain
    `file.html -> /file` rule this gate has always used.
    """
    rel = str(rel or "")
    if rel.endswith("/index.html"):
        rel = rel[:-len("index.html")]
    elif rel.endswith(".html"):
        rel = rel[:-len(".html")]
    return f"{DOMAIN}/{rel.rstrip('/')}"


